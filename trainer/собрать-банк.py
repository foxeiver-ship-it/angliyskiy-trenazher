#!/usr/bin/env python3
"""Собирает trainer/build/банк.js из базы вопросов проекта-источника.

Источник: ~/Documents/Экзамен-английский/база.json — там уже лежат и разборы
(поля e/w/k), и тема каждого вопроса.

Запуск: python3 trainer/собрать-банк.py
"""

import json
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ИСТОЧНИК = Path.home() / "Documents" / "Экзамен-английский" / "база.json"
ВЫХОД = КОРЕНЬ / "trainer" / "build" / "банк.js"

ТИПЫ = {"multichoice": "one", "shortanswer": "short", "match": "match", "reading": "one"}

# порядок тем в тренажёре: сначала грамматика, потом лексика
ПОРЯДОК_ТЕМ = [
    "Времена и согласование времён",
    "Условные предложения и модальные глаголы",
    "Инфинитив, герундий и управление глагола",
    "Косвенная речь, придаточные и порядок слов",
    "Местоимения, определители, артикли",
    "Степени сравнения и наречия",
    "Словообразование и паронимы",
    "Лексика и устойчивые сочетания",
    "Соответствие: дефиниции понятий",
]


def разобрать_пары(текст):
    пары = []
    for строка in текст.splitlines():
        if "→" in строка:
            слева, справа = строка.split("→", 1)
            пары.append({"l": слева.strip(), "r": справа.strip()})
    return пары


def main():
    база = json.loads(ИСТОЧНИК.read_text(encoding="utf-8"))

    встречены = {в["тема"] for в in база}
    неизвестные = встречены - set(ПОРЯДОК_ТЕМ)
    if неизвестные:
        raise SystemExit("Темы вне рубрикатора: " + ", ".join(sorted(неизвестные)))
    темы = [т for т in ПОРЯДОК_ТЕМ if т in встречены]
    номер = {т: i for i, т in enumerate(темы)}

    банк = []
    for в in база:
        вопрос = {
            "id": в["id"],
            "t": номер[в["тема"]],
            "ty": ТИПЫ[в["тип"]],
            "q": в["текст"].strip(),
            "o": [],
            "a": [],
            "pairs": [],
            "pool": [],
            "ans": "",
            "img": None,
            "oimg": [],
            "e": в["e"],
            "w": [],
            "k": в["k"],
        }
        if в["тип"] in ("multichoice", "reading"):
            вопрос["o"] = [х["текст"].strip() for х in в["варианты"]]
            вопрос["a"] = [i for i, х in enumerate(в["варианты"]) if х["верный"]]
            вопрос["w"] = в["w"]
            вопрос["oimg"] = [None] * len(вопрос["o"])
            if len(вопрос["a"]) > 1 or в.get("несколько_ответов"):
                вопрос["ty"] = "many"
        elif в["тип"] == "shortanswer":
            вопрос["ans"] = в["ответ"].strip()
        else:
            вопрос["pairs"] = разобрать_пары(в["ответ"])
            вопрос["pool"] = sorted({о for п in в["пары"] for о in п["варианты"]})
        банк.append(вопрос)

    строки = [
        "// Файл собран скриптом trainer/собрать-банк.py — правки вносите в источники.",
        "window.ТЕМЫ = "
        + json.dumps(
            [{"n": i, "название": т} for i, т in enumerate(темы)], ensure_ascii=False
        )
        + ";",
        "window.БАНК = [",
    ]
    строки += [json.dumps(в, ensure_ascii=False) + "," for в in банк]
    строки.append("];")
    ВЫХОД.write_text("\n".join(строки) + "\n", encoding="utf-8")

    print(f"Вопросов: {len(банк)}, тем: {len(темы)}")


if __name__ == "__main__":
    main()
